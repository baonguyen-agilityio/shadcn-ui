// Helper function to get cars by status
export const getCarsByStatus = (status: Car['carStatus']) => {
  return sampleCars.filter(car => car.carStatus === status);
};

// Helper function to get cars by make
export const getCarsByMake = (make: string) => {
  return sampleCars.filter(
    car => car.make.toLowerCase() === make.toLowerCase()
  );
};

// Helper function to get cars by price range
export const getCarsByPriceRange = (minPrice: number, maxPrice: number) => {
  return sampleCars.filter(
    car => car.price >= minPrice && car.price <= maxPrice
  );
};

// Helper function to get cars by year range
export const getCarsByYearRange = (minYear: number, maxYear: number) => {
  return sampleCars.filter(car => car.year >= minYear && car.year <= maxYear);
};
